// Package clinical 提供在本机运行的临床档案与授权查阅能力，只处理合成患者资料。
//
// 基本用法是先用 [Open] 在调用方指定的数据目录打开一个 [Store]：
//
//	s, err := clinical.Open("/path/to/data")
//
// 所有写操作都由内部使用者（[InternalActor]）执行：登记患者（Store.RegisterPatient）、
// 登记就诊（Store.AddEncounter）、在就诊下录入诊断或医嘱草稿
// （Store.CreateDraft / Store.UpdateDraft / Store.DeleteDraft），草稿确认后
// 用 Store.ActivateRecord 生效。生效记录不可覆盖或删除，只能用
// Store.CorrectRecord 更正：更正需提供非空原因并指明显式当前版本号，
// 成功后生成新版本，旧内容、版本关系（Version.PrevID）与原因全部保留；
// 指定版本已过期则返回 [ErrConflict] 且状态不变。
//
// 内部使用者用 Store.Chart 查看某患者的全部草稿与完整版本历史；
// 用 Store.Grant 为接收方（[ReceiverActor]）建立按“就诊+类别”限定、
// 带 [开始, 截止) 时间窗的整类授权，或用 Store.GrantSelective 在整类
// 范围之外再明确选出若干已生效记录（整类范围与选定记录范围可并存、
// 可跨多个就诊与类别），可用 Store.Revoke 提前撤回。
// 接收方用 Store.Read 按自己的身份读取：只返回所有当前有效授权允许记录
// 的当前生效版本合集，每条记录只出现一次；看不到草稿、旧版本或更正原因。
// 被选记录被更正后读到当前版本，但同类其他记录与后来新增生效的记录不会
// 自动进入限定范围；撤回整类授权后只剩其他有效授权明确允许的记录。
//
// 内部使用者可用 Store.CreateExchange 把一条当前有效授权覆盖的已生效记录
// 集合打包给指定接收方：所选每条记录都必须被绑定的那一条授权自身覆盖
// （整类或选定记录），不能借用同一接收方的其他授权补足；包只含患者与
// 接收方标识及各记录创建时的当前版本（就诊、类别、记录与版本标识、版本号、
// 生效时间与完整内容），并附稳定摘要，状态为待回执；包一旦创建即固定，
// 此后的更正或新增记录不会改写它。
// 请求号按内部使用者区分，相同请求号与相同参数重试返回原交换及其现有状态。
// 接收方用 Store.FetchPackage 取包（按等待结束、真正开始核对本次取包权限的
// 时刻重新检查绑定授权与患者状态；提前发出的请求不会延长授权有效期，
// 其他有效授权不能替代绑定授权），
// 用 Store.SubmitReceipt 凭交换标识与包摘要登记接受或拒绝回执；授权失效或
// 患者停用后取包被拒绝，但此前包的回执仍可登记。内部使用者可用
// Store.GetExchange / Store.ListExchanges 按患者查看原包与回执，停用后亦可。
//
// 停用档案（Store.DeactivatePatient）后禁止一切写入与接收方读取，
// 内部使用者仍可查看历史。生效、更正、授权创建与撤回、档案停用、交换创建与
// 首次回执登记都会写入仅供内部使用者按患者查看的审计事件。关闭后用同一目录
// 重新 [Open]，档案、版本、授权状态、交换、回执与审计历史全部保留；
// 授权是否到期始终按本次读取时间判断。
//
// [Ready] 保持基线行为：包可以加载时始终返回 true。
package clinical

// Ready 表示基线可以运行。
func Ready() bool { return true }
